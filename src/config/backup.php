<?php

return [

    /*
    |--------------------------------------------------------------------------
    | バックアップ保存先ディレクトリ
    |--------------------------------------------------------------------------
    |
    | mysqldump → openssl で作成した暗号化ファイルを一時的に保存するローカル
    | ディレクトリ。`db:backup` はここに書き出してからバックアップ用ストレージ
    | にアップロードし、成功後にローカルファイルを削除する。
    |
    | 未設定のまま動作させると意図しない場所への書き込みや、空文字でのパス結合
    | による失敗を招くため、デフォルトは持たない。呼び出し側のガード節で空・
    | 不存在を検出させる。
    |
    */

    'directory' => env('BACKUP_DIRECTORY'),

    /*
    |--------------------------------------------------------------------------
    | バックアップ暗号化鍵
    |--------------------------------------------------------------------------
    |
    | openssl AES-256-CBC + PBKDF2 で暗号化・復号する際に使うパスフレーズ。
    |
    | 空値を許すと暗号化強度が実質失われるため、デフォルトは持たない。呼び出し
    | 側のガード節で空を検出させる。
    |
    */

    'encryption_key' => env('BACKUP_ENCRYPTION_KEY'),

    /*
    |--------------------------------------------------------------------------
    | mysqldump 実行パス
    |--------------------------------------------------------------------------
    |
    | `db:backup` で DB をダンプするために呼び出す mysqldump コマンドのパス。
    |
    | Linux 本番 : `mysqldump` で PATH 解決可能なため未設定でよい（デフォルト 'mysqldump'）。
    | Windows 開発: 開発サーバー（Herd / php -S）の子プロセスでは PATH 解決に
    |               失敗するため、`.env` で mysqldump.exe のフルパスを指定する。
    |
    */

    'mysqldump_path' => env('MYSQLDUMP_PATH', 'mysqldump'),

    /*
    |--------------------------------------------------------------------------
    | mysql 実行パス
    |--------------------------------------------------------------------------
    |
    | `db:restore` で復号後の SQL を流し込むために呼び出す mysql コマンドのパス。
    |
    | Linux 本番 : `mysql` で PATH 解決可能なため未設定でよい（デフォルト 'mysql'）。
    | Windows 開発: 開発サーバー（Herd / php -S）の子プロセスでは PATH 解決に
    |               失敗するため、`.env` で mysql.exe のフルパスを指定する。
    |
    */

    'mysql_path' => env('MYSQL_PATH', 'mysql'),

    /*
    |--------------------------------------------------------------------------
    | openssl 実行パス
    |--------------------------------------------------------------------------
    |
    | バックアップの暗号化・復号で呼び出す openssl コマンドのパス。
    |
    | Linux 本番 : `openssl` で PATH 解決可能なため未設定でよい（デフォルト 'openssl'）。
    | Windows 開発: 開発サーバー（Herd / php -S）の子プロセスでは PATH 解決に
    |               失敗するため、`.env` で openssl.exe のフルパスを指定する。
    |
    */

    'openssl_path' => env('OPENSSL_PATH', 'openssl'),

];
